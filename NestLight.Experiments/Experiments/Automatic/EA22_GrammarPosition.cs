using System.Linq;
using NestLight.Completion;

namespace NestLight.Experiments
{
    internal sealed class EA22_GrammarPosition : Experiment
    {
        public override string Id { get { return "EA22"; } }
        public override string Title { get { return "Does the place in the grammar help to rank the suggestions?"; } }
        public override string Hypothesis { get { return "What belongs at the caret can be told from a few characters of look-behind: a table after `from`, a column after `select`, `by` after `group`, the properties inside the braces of CSS and the values of the property after its colon, the attributes of the tag inside `<button `. Putting what belongs first and what does not last puts the meant word in the first 5 more often than the previous word and the language alone, in every language that has a grammar, and it fits in a frame."; } }
        public override string Method { get { return "EA20's probes (50 generated files with structure, words typed with 1 to 3 letters, the list the editor gets). Four variants: the order by distance alone; the grammar; the previous word and the language (what the plugin ran with before this experiment); all three. Reported by the place of the caret. Also the start of a session on files of 1,200 to 60,000 lines."; } }
        public override string Criterion { get { return "Adding the grammar to the previous word and the language is at least 2 points better within the first 5 over all the reachable cases; SQL, CSS and HTML each do not fall; and the session with all three stays under 16 ms at 60,000 lines, in every host."; } }
        public override string IfMet { get { return "Keep the grammar on."; } }
        public override string IfNotMet { get { return "Look at the table by place: a place that loses points is a rule to fix or to drop."; } }

        public override Outcome Run(Settings settings)
        {
            var outcome = new Outcome();
            var corpus = SyntheticCorpus.Generate(settings.Quick ? 8 : 50, 4321, 0.5, 40, true);
            var probes = ContextLab.Probes(corpus, settings.Quick ? 20 : 60, 3);
            ContextLab.MarkReachable(probes);

            var names = new[] { "By distance alone", "Grammar", "Previous word and language", "All three" };
            var features = new[]
            {
                CompletionFeatures.None,
                new CompletionFeatures(grammar: true),
                new CompletionFeatures(previousWord: true, sameLanguageWords: true),
                new CompletionFeatures(previousWord: true, sameLanguageWords: true, grammar: true),
            };
            var factories = features.Select(ContextLab.Plugin).ToArray();
            ContextLab.Comparison c = ContextLab.Compare(probes, names, factories);
            ContextLab.AddTables(outcome, c, "The word typed with 1 to 3 letters", 6, true);

            double worst; string worstCase;
            outcome.Tables.Add(ContextLab.Latency(settings, names, factories, "comp", out worst, out worstCase));

            double gain = c.Rate(3, p => true, 5) - c.Rate(2, p => true, 5);
            var languages = new[] { "sql", "css", "html" };
            double worstLanguage = languages.Select(id => c.Rate(3, p => p.EmbeddedLanguageId == id, 5) - c.Rate(2, p => p.EmbeddedLanguageId == id, 5)).Min();
            outcome.CriterionMet = gain >= 2 && worstLanguage >= 0 && worst < 16;
            outcome.Headline = "within the first 5: " + ContextLab.Pct(c.Rate(2, p => true, 5)) + " to " + ContextLab.Pct(c.Rate(3, p => true, 5)) + " (" + ContextLab.Signed(gain) + " points); worst session " + Measure.Ms(worst);
            outcome.Analysis.Add("The grammar alone moves the share within the first 5 from " + ContextLab.Pct(c.Rate(0, p => true, 5)) + " to " + ContextLab.Pct(c.Rate(1, p => true, 5)) + "; added to the previous word and the language, " + ContextLab.Signed(gain) + " points; the worst of SQL, CSS and HTML changes by " + ContextLab.Signed(worstLanguage) + " points.");
            outcome.Analysis.Add("The slowest session with all three at the largest size is " + worstCase + ": " + Measure.Ms(worst) + " (the frame budget is 16 ms).");
            outcome.Analysis.Add("The corpus is generated by the same person who wrote the rules of the grammar, and it follows them: the attributes of a tag are the ones in the table of attributes, the values of a property the ones in the table of values. A real file will have words the tables do not know, and the grammar then costs nothing but gains nothing. This experiment says the rules do not get in the way of code that follows them, not how often real code does.");
            return outcome;
        }
    }
}
